// 2D board geometry → printable relief solid (manifold-3d).
import type { ManifoldToplevel, Manifold, CrossSection as CS } from 'manifold-3d';
import type { BoardGeometry, Ring } from './geometry';

export interface ModelSettings {
  /** Substrate thickness, mm. */
  substrate: number;
  /** Copper relief height above the substrate, mm. */
  relief: number;
  /** Which copper layer forms the relief. */
  side: 'top' | 'bottom';
}

export interface MeshData {
  positions: Float32Array; // xyz per vertex, mm
  indices: Uint32Array; // 3 per triangle
  volume: number;
  triangles: number;
}

const HOLE_SEGMENTS_TOL = 0.01;

function circleSegments(r: number) {
  const step = r > HOLE_SEGMENTS_TOL ? 2 * Math.acos(1 - HOLE_SEGMENTS_TOL / r) : Math.PI / 4;
  return Math.max(12, Math.ceil((2 * Math.PI) / step));
}

/**
 * Single-sided relief board: substrate in the board outline, copper raised on
 * top of it (clipped to the outline), every drill and slot cut through both.
 * Bottom copper is mirrored so the relief reads correctly from the printed side.
 */
export function buildRelief(m: ManifoldToplevel, g: BoardGeometry, s: ModelSettings): { mesh: MeshData; warnings: string[] } {
  const warnings: string[] = [];
  const trash: { delete(): void }[] = [];
  const keep = <T extends { delete(): void }>(x: T) => (trash.push(x), x);
  const cs = (rings: Ring[]) => keep(rings.length ? new m.CrossSection(rings, 'NonZero') : m.CrossSection.square(0));

  try {
    if (!g.outline.length) throw new Error('No closed board outline — assign the outline layer first.');
    const copper = s.side === 'top' ? g.copperTop : g.copperBottom;
    if (!copper.length) warnings.push(`No ${s.side} copper: the model is a bare substrate.`);

    const outline = cs(g.outline);
    const copperCs = keep(cs(copper).intersect(outline));

    // All holes as one 2D cut.
    const cuts: CS[] = [cs(g.slots)];
    for (const h of g.holes) cuts.push(keep(m.CrossSection.circle(h.d / 2, circleSegments(h.d / 2)).translate([h.x, h.y])));
    const holes2d = keep(m.CrossSection.union(cuts));

    const total = s.substrate + s.relief;
    const substrate = keep(outline.extrude(s.substrate));
    const relief = keep(keep(copperCs.extrude(s.relief)).translate([0, 0, s.substrate]));
    const drill = keep(keep(holes2d.extrude(total + 2)).translate([0, 0, -1]));
    let solid: Manifold = keep(keep(substrate.add(relief)).subtract(drill));
    if (s.side === 'bottom') {
      // Mirror in X, then shift back so the board keeps its original footprint.
      const { min, max } = solid.boundingBox();
      solid = keep(keep(solid.mirror([1, 0, 0])).translate([min[0] + max[0], 0, 0]));
    }

    const mesh = solid.getMesh();
    const n = mesh.numProp;
    const positions = new Float32Array((mesh.vertProperties.length / n) * 3);
    for (let i = 0, j = 0; i < mesh.vertProperties.length; i += n, j += 3) {
      positions[j] = mesh.vertProperties[i];
      positions[j + 1] = mesh.vertProperties[i + 1];
      positions[j + 2] = mesh.vertProperties[i + 2];
    }
    return {
      mesh: { positions, indices: new Uint32Array(mesh.triVerts), volume: solid.volume(), triangles: solid.numTri() },
      warnings,
    };
  } finally {
    for (const t of trash) t.delete();
  }
}

/** Binary STL (little-endian), units mm. */
export function toStl(mesh: MeshData, name = 'fdm-pcb'): Blob {
  const tris = mesh.indices.length / 3;
  const buf = new ArrayBuffer(84 + tris * 50);
  const dv = new DataView(buf);
  const header = `${name} - generated by FDM-PCB`.slice(0, 80);
  for (let i = 0; i < header.length; i++) dv.setUint8(i, header.charCodeAt(i) & 0x7f);
  dv.setUint32(80, tris, true);
  const p = mesh.positions;
  let o = 84;
  for (let t = 0; t < tris; t++) {
    const a = mesh.indices[3 * t] * 3, b = mesh.indices[3 * t + 1] * 3, c = mesh.indices[3 * t + 2] * 3;
    const ux = p[b] - p[a], uy = p[b + 1] - p[a + 1], uz = p[b + 2] - p[a + 2];
    const vx = p[c] - p[a], vy = p[c + 1] - p[a + 1], vz = p[c + 2] - p[a + 2];
    let nx = uy * vz - uz * vy, ny = uz * vx - ux * vz, nz = ux * vy - uy * vx;
    const len = Math.hypot(nx, ny, nz) || 1;
    nx /= len; ny /= len; nz /= len;
    for (const v of [nx, ny, nz, p[a], p[a + 1], p[a + 2], p[b], p[b + 1], p[b + 2], p[c], p[c + 1], p[c + 2]]) {
      dv.setFloat32(o, v, true);
      o += 4;
    }
    o += 2; // attribute byte count
  }
  return new Blob([buf], { type: 'model/stl' });
}

export type PartName = 'single' | 'top' | 'bottom';

export interface BoardSettings {
  sides: 1 | 2;
  /** Substrate of a single-sided board, mm. */
  substrate: number;
  /** Substrate of each half of a double-sided board, mm. */
  halfSubstrate: number;
  relief: number;
  /** Relief side for a single-sided board. */
  side: 'top' | 'bottom';
}

/**
 * Single-sided: one part. Double-sided: the board is cut through the middle of
 * the substrate into two halves, each printed flat side down with its own
 * copper relief. The bottom half is mirrored, so flipping it over puts every
 * hole back above the matching hole of the top half.
 */
export function buildBoard(m: ManifoldToplevel, g: BoardGeometry, s: BoardSettings) {
  if (s.sides === 1) {
    const r = buildRelief(m, g, { substrate: s.substrate, relief: s.relief, side: s.side });
    return { parts: [{ part: 'single' as PartName, mesh: r.mesh }], warnings: r.warnings };
  }
  const top = buildRelief(m, g, { substrate: s.halfSubstrate, relief: s.relief, side: 'top' });
  const bottom = buildRelief(m, g, { substrate: s.halfSubstrate, relief: s.relief, side: 'bottom' });
  return {
    parts: [
      { part: 'top' as PartName, mesh: top.mesh },
      { part: 'bottom' as PartName, mesh: bottom.mesh },
    ],
    warnings: [...top.warnings, ...bottom.warnings],
  };
}
